#Requires -Version 7
<#
.SYNOPSIS
    Checks that a lithium blanket bolted to a running reactor breeds tritium from lithium, that it
    stops when either the lithium or the reactor stops, and that removing it leaves the reactor
    working. Discharges #30.

.DESCRIPTION
    Blanket breeding is the second of the two routes CONTEXT.md names, and the one real D-T
    machines are designed around: the plasma cannot confine its neutrons, so a shell of lithium
    around it catches them and breeds tritium. tests/test-reactor-logic.lua asserts the arithmetic;
    this asserts that the arithmetic reaches a pipe, spends an item, and stops when it should.

    WHY THE TRITIUM COMES OUT OF THE COLLECTOR

    The blanket is a plain container -- lithium is an item, so it needs an inventory and nothing
    else -- and what it breeds leaves through the rf-isotope-collector already bolted to the same
    reactor. prototypes/entities.lua says why: no 2.0.77 prototype is simply "inventory plus fluid
    box", and the two that come close bring machinery that would have to be neutered. The visible
    consequence is that a blanket without a collector is idle, which is the `orphan` cell below.

    THE CONTROL THAT MAKES THIS MEAN ANYTHING

    A D-T reactor breeds NOTHING on its own -- its products table is empty, because the alpha is
    helium-4 and the neutron is already what the mod sells as reactor energy. So every unit of
    tritium the `fitted` cell collects came from the blanket, and the `bare` cell must collect
    exactly zero. That is a far stronger statement than "more with than without", and it is only
    available on this tier.

    WHAT IS BUILT

      fitted     A D-T reactor with a collector and a blanket loaded with lithium. It must breed
                 tritium into the collector, and must spend lithium doing it.
      bare       The same D-T reactor and collector with no blanket at all. It must collect
                 nothing, which is what says the tritium above came from the blanket.
      empty      A blanketed D-T reactor whose blanket was never loaded. Breeds nothing, and the
                 reactor runs exactly as well.
      orphan     A loaded blanket on a reactor with NO collector. Its lithium must be untouched:
                 a blanket with nowhere to put what it breeds stays idle rather than spending
                 items for nothing.
      throttled  A blanketed reactor whose collector is drained far more slowly than the blanket
                 can fill it. Every item spent must be accounted for by a triton still in the
                 collector or drawn out of it -- a blanket must not buy tritium that is being
                 discarded. Drained rather than merely unplumbed, because a saturated box has
                 exactly zero headroom and exercises an early return instead of the cap.
      pulled     A blanketed reactor whose blanket is destroyed halfway through. The reactor has
                 to go on running and go on producing energy.
      d-d        A D-D reactor with a collector and a loaded blanket. It must collect MORE tritium
                 than helium-3 -- the by-product route and the blanket route arriving in the same
                 box -- where an unblanketed D-D reactor collects them in equal measure.

.PARAMETER FactorioExe
    Path to Factorio.exe. Defaults to $env:FACTORIO_EXE, then the Steam install on this machine.

.PARAMETER Ticks
    Ticks to run before checking. The default is long enough for a D-T reactor to have ignited and
    for a blanket to have worked through several lithium items.

.PARAMETER KeepTemp
    Keep the save, the rig mod and the captured output.

.EXAMPLE
    pwsh -File scripts/check-blanket.ps1
#>
[CmdletBinding()]
